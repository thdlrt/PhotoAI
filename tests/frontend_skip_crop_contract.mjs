import fs from "node:fs";
import vm from "node:vm";
import assert from "node:assert/strict";
const context = vm.createContext({document:{addEventListener(){}},console,setTimeout,clearTimeout});
vm.runInContext(fs.readFileSync(process.argv[2],"utf8"),context);
const run = code => vm.runInContext(code,context);
const requests = [], stages = [], messages = [];
context.request = (path,options) => requests.push({path,...options});
context.stage = value => stages.push(value);
context.notice = value => messages.push(value);
run(`renderReview = () => {}; syncDevelopSummary = () => {}; toast = value => notice(value);
  goWorkflowStage = async value => stage(value);
  loadDevelop = async () => {throw new Error('unexpected AI generation');};
  requireModelSetupUi = async () => {throw new Error('unexpected model check');};
  state.currentRun = {run_id:'chosen-run', input_root:'C:/photos/chosen', review_revision:7, xmp_ready:true};
  state.developProgress = {status:'cancelled'};
  api = async (path, options) => {request(path,options); return {exists:true,crop_skipped:true,eligible_count:2,confirmed_count:2};};`);
await run("skipAutomaticCrop()");
assert.equal(requests[0].path,"/api/runs/chosen-run/develop/skip-analysis");
assert.equal(requests[0].method,"POST");
assert.equal(requests[0].body.base_revision,7);
assert.deepEqual(stages,["base"]);
assert.equal(run("state.developPlan.crop_skipped"),true);
assert.equal(run("state.developProgress"),null);
assert.equal(run("state.developBusy"),false);
run("state.activeJob = {id:'own',kind:'develop',status:'running',context:{run_id:'chosen-run'}}");
await run("skipAutomaticCrop()");
assert.equal(requests.length,1);
run("state.activeJob = null; api = async () => {throw new Error('审片已变化，请刷新后重试。');}");
await run("skipAutomaticCrop()");
assert.equal(stages.length,1);
assert.equal(run("state.developBusy"),false);
assert.match(messages[0],/审片已变化/);
console.log("skip automatic crop: direct base-stage entry, no AI, locked task guard and error recovery PASS");
